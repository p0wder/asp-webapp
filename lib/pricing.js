/**
 * Price for a single print location.
 * @param {number} qty - Total quantity
 * @param {number} colors - Ink colors (1–6)
 * @param {boolean} isAdditional - true for 2nd+ locations (uses "Add L" columns)
 */
export function getPrice(qty, colors, isAdditional) {
  if (qty < 1 || colors < 1) return 0;
  const row = lookupRow(qty);
  const c = Math.max(1, Math.min(6, colors));
  return isAdditional ? row[6 + c] : row[c];
}

/**
 * Total per-shirt unit cost across all active print locations.
 * @param {string|number} qty - Quantity (will be parseInt'd)
 * @param {number} inkColors - Colors for the first/only location (used when locsEnabled=false)
 * @param {boolean} locsEnabled - Whether per-location breakdown is active
 * @param {Array<{colors: number}>} locations - Array of location objects
 * @returns {number|null} Unit cost, or null if qty < 1
 */
export function calcUnitCost(qty, inkColors, locsEnabled, locations) {
  const q = parseInt(qty) || 0;
  if (q < 1) return null;
  if (!locsEnabled) {
    return getPrice(q, inkColors, false);
  }
  let price = 0;
  locations.forEach((loc, i) => {
    price += getPrice(q, loc.colors, i > 0);
  });
  return price;
}
